from typing import Protocol, Any

class MarketDataProvider(Protocol):
    def fetch_snapshot(self, symbol: str) -> dict[str, Any]: ...

class NewsProvider(Protocol):
    def fetch_events(self, symbol: str) -> list[dict[str, Any]]: ...

class BrokerCatalogue(Protocol):
    def check_instrument(self, broker: str, symbol: str, direction: str) -> dict[str, Any]: ...

class AlertSink(Protocol):
    def send_qualified_alert(self, message: str, idempotency_key: str) -> None: ...
